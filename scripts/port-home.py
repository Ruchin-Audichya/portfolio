"""Generate the Next.js homepage from the standalone design file.

    python3 scripts/port-home.py            # reads design/home.html

design/home.html is a self-contained page (open it in a browser to preview).
This script scopes its CSS under .ra, extracts the markup and script, and writes
src/components/home/{home.css, markup.ts, initHome.ts}. Theme switching on the
site is handled by next-themes (html.light / html.dark), see HomeEffects.tsx.
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "design", "home.html")
OUT = os.path.join(ROOT, "src", "components", "home")

html = open(SRC, encoding="utf-8").read()
css = html.split("<style>", 1)[1].split("</style>", 1)[0]
markup = html.split("</style>", 1)[1].split("<script>", 1)[0]
script = html.split("<script>", 1)[1].rsplit("</script>", 1)[0]

# ---------- CSS ----------
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
css = css[css.index("*{box-sizing"):]  # drop the standalone theme blocks; tokens below replace them

TOKENS = """
.ra{
  --paper:#111110; --panel:#1A1A18; --ink:#ECECE5; --muted:#9A9A92; --rule:#2E2E2B;
  --rani:#FF5C93; --indigo:#93A4FF; --marigold:#F2B632; --wash:rgba(255,92,147,.09);
  --bg:var(--paper);
  --sans:var(--f-sans), "Helvetica Neue", Arial, system-ui, sans-serif;
  --deva:var(--f-deva), "Noto Serif Devanagari", "Kohinoor Devanagari", serif;
  --mono:var(--f-mono), ui-monospace, Menlo, Consolas, monospace;
  --pixel:var(--f-pixel), var(--f-mono), monospace;
  --ease:cubic-bezier(.2,.8,.2,1);
  color-scheme:dark; min-height:100vh;
}
html.light .ra{
  --paper:#F3F3EF; --panel:#FFFFFF; --ink:#151515; --muted:#6A6A64; --rule:#D8D7D0;
  --rani:#C8205E; --indigo:#2D3E9E; --marigold:#B87E00; --wash:rgba(200,32,94,.07); color-scheme:light;
}
"""

def blocks(s):
    out, i = [], 0
    while True:
        j = s.find("{", i)
        if j < 0:
            return out
        depth, k = 1, j + 1
        while depth:
            depth += {"{": 1, "}": -1}.get(s[k], 0)
            k += 1
        out.append((s[i:j].strip(), s[j + 1:k - 1]))
        i = k

def scope_selector(sel):
    parts = []
    for p in (x.strip() for x in sel.split(",")):
        if p in ("body", "html"):
            parts.append(".ra")
        elif p.startswith("body::before"):
            return None
        elif p == "*":
            parts.append(".ra *")
        elif p.startswith(".motion "):  # .motion is set on <html>, an ancestor of .ra
            parts.append(".motion .ra " + p[len(".motion "):])
        else:
            parts.append(".ra " + p)
    return ",".join(parts)

def scope(s):
    res = []
    for sel, body in blocks(s):
        if sel.startswith("@keyframes"):
            res.append(f"{sel}{{{body}}}")
        elif sel.startswith("@media"):
            res.append(f"{sel}{{{scope(body)}}}")
        else:
            new = scope_selector(sel)
            if new is None:
                continue
            if new == ".ra" and body.strip().rstrip(";").startswith("scroll-behavior") and ";" not in body.strip().rstrip(";"):
                continue  # Lenis owns scrolling on the site
            res.append(f"{new}{{{body}}}")
    return "\n".join(res)

scoped = (TOKENS + scope(css)).replace("overflow-x:hidden", "overflow-x:clip")  # hidden would break the sticky bar
os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, "home.css"), "w", encoding="utf-8").write(
    "/* Generated by scripts/port-home.py from design/home.html. Scoped to .ra so it cannot leak into other routes. */\n" + scoped + "\n")

# ---------- markup ----------
open(os.path.join(OUT, "markup.ts"), "w", encoding="utf-8").write(
    "// Generated by scripts/port-home.py from design/home.html. Server-rendered homepage markup.\n"
    f"export const homeMarkup = {json.dumps(markup.strip(), ensure_ascii=False)};\n")

# ---------- script ----------
body = script.strip()
assert body.startswith("(() => {") and body.endswith("})();")
body = body[len("(() => {"):-len("})();")]
needle = "const css = n => getComputedStyle(document.documentElement).getPropertyValue(n).trim();"
assert needle in body
body = body.replace(needle, "const css = n => getComputedStyle(raEl).getPropertyValue(n).trim();")
body, n = re.subn(r"/\* ---------- theme toggle ---------- \*/.*?(?=/\* ---------- copy email)", "", body, flags=re.S)
assert n == 1, "theme toggle block not found"
body = body.replace("requestAnimationFrame(", "raf(")
body = body.replace("setInterval(tick, 20000);", "timers.push(setInterval(tick, 20000));")
open(os.path.join(OUT, "initHome.ts"), "w", encoding="utf-8").write(
    "// @ts-nocheck\n"
    "// Generated by scripts/port-home.py from design/home.html. Client behaviour for the homepage.\n"
    "export function initHome(raEl: HTMLElement): () => void {\n"
    "  let alive = true;\n"
    "  const timers: number[] = [];\n"
    "  const raf = (f) => { if (alive) requestAnimationFrame(f); };\n"
    + body +
    "\n  return () => { alive = false; timers.forEach(clearInterval); document.documentElement.classList.remove('motion'); };\n}\n")
print("wrote home.css, markup.ts, initHome.ts")
